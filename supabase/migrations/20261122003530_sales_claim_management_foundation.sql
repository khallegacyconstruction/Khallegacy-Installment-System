insert into public.permissions (permission_key, description)
values ('sales_claim', 'Manage Sales Claim fees and JCL claim reconciliation')
on conflict (permission_key) do update set description = excluded.description;

insert into public.role_permissions (role_id, permission_key)
select r.id, 'sales_claim' from public.roles r where r.name = 'Management'
on conflict do nothing;

create table public.sales_claim_batches (
  id uuid primary key default gen_random_uuid(),
  batch_reference text not null unique,
  sale_submission_id text not null references public.sale_submissions(submission_list_id),
  jcl_batch_reference text,
  received_date date not null,
  remarks text not null default '',
  created_by_staff_id text references public.staff_users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.sales_claim_records (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.sales_claim_batches(id) on delete restrict,
  application_id bigint references public.applications(id) on delete set null,
  case_id text not null,
  ic_number text not null,
  customer_name text not null default '',
  item text not null default '',
  finance_amount numeric(12,2) not null default 0,
  deposit numeric(12,2) not null default 0,
  stamp_duty_fee numeric(12,2) not null default 0,
  processing_fee numeric(12,2) not null default 50,
  sst_amount numeric(12,2) not null default 4,
  actual_cash_payment numeric(12,2) not null default 0,
  branch text not null default '',
  invoice_number text not null default '',
  staff_1 text not null default '',
  staff_2 text not null default '',
  claim_date date,
  claim_status text not null default 'NOT YET CLAIMED'
    check (claim_status in ('CLAIMED','NOT YET CLAIMED','DISCREPANCY','PENDING VERIFICATION','CANCELLED')),
  investigation_status text not null default 'NOT REVIEWED'
    check (investigation_status in ('NOT REVIEWED','UNDER REVIEW','WAITING JCL','RESOLVED','FOLLOW UP')),
  remarks text not null default '',
  entered_by_staff_id text references public.staff_users(id) on delete set null,
  entered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index sales_claim_records_batch_application_unique
on public.sales_claim_records(batch_id, application_id) where application_id is not null;
create index sales_claim_records_batch_status_idx on public.sales_claim_records(batch_id, claim_status);
create index sales_claim_records_case_ic_idx on public.sales_claim_records(case_id, ic_number);

create table public.sales_claim_history (
  id bigint generated by default as identity primary key,
  sales_claim_record_id uuid not null references public.sales_claim_records(id) on delete restrict,
  event_type text not null,
  old_value text,
  new_value text,
  notes text not null default '',
  changed_by_staff_id text references public.staff_users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.sales_claim_batches enable row level security;
alter table public.sales_claim_records enable row level security;
alter table public.sales_claim_history enable row level security;

